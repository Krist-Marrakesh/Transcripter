"""Кто скрывается за ярлыками «Спикер 1», «Спикер 2».

Диаризация отвечает на «кто когда говорит» по тембру голоса и имён знать не
может — их в звуке нет. Зато они есть в самой речи: люди представляются и
называют друг друга. Поэтому это проход по готовому тексту, а не часть разметки.

Промты здесь русские намеренно, как и в соседних модулях: они просят разбирать
русскую речь, и от их языка зависит ответ. Это работающий текст, а не комментарий.
"""

from __future__ import annotations

import re

from ..models import Transcript
from .llm import LLM

_SYSTEM = (
    "Ты разбираешь расшифровки бесед. Опираешься только на текст и ничего не "
    "додумываешь: назвать человека наугад хуже, чем оставить его безымянным."
)

_PROMPT = """Ниже начало расшифровки. Реплики подписаны условными ярлыками.

Определи, как зовут говорящих. Учти главное: человека чаще называет не он сам, а
собеседник или ведущий — «сегодня против нас Ларин». Тогда имя относится к тому,
о ком говорят, и искать его надо среди тех, кто говорит рядом и много, а не среди
тех, кто обронил пару слов.

Ответь по строке на каждого, кого удалось узнать:

Спикер 1 = Имя

Кого назвать не по чему — просто пропусти, не выдумывай. Имя пиши так, как оно
звучит в записи, без пояснений и без должностей.

Расшифровка:
{text}"""

# «Спикер 1 = Юрий Хованский», но модель нет-нет да поставит тире или двоеточие.
_PAIR = re.compile(r"^\s*(.+?)\s*[=—–:-]\s*(.+?)\s*$")

# Строка формата, повторённая моделью вместо ответа, и вежливые отказы: имя,
# состоящее из слова «имя», — это не имя.
_NOT_A_NAME = frozenset({"имя", "неизвестно", "не указано", "нет", "-", "—"})


def name_speakers(transcript: Transcript, llm: LLM, *, sample_chars: int = 6000) -> dict[str, str]:
    """Ярлык → человек, для тех, кого удалось узнать.

    Хватает начала записи: имена звучат при знакомстве. Замерено на двух баттлах
    — все ключевые имена попадают в первые 3200 символов («Слава КПСС» на 601-м,
    «Мирон» на 1260-м, «Оксимирон» на 3216-м; «Ларин» и «Хованский» на 31-м и
    85-м). Шесть тысяч — тот же размер куска, что берут перевод и саммари; на
    двенадцати тысячах модель начала выдавать одному человеку два ярлыка.

    **Точность держится на разметке под ней.** На баттле, где диаризация нашла
    троих, названы верно все трое. На соседнем, где та же диаризация накрошила
    девять ярлыков на тех же троих, верны двое из четырёх: ярлыкам-обрывкам не
    соответствует никто, и имя для них взять неоткуда. Число спикеров, если оно
    известно, поднимает и эту половину тоже.
    """
    labels = set(transcript.speakers)
    if not labels:
        return {}

    answer = llm.complete(
        _PROMPT.format(text=_opening(transcript, sample_chars)),
        system=_SYSTEM,
        max_tokens=200,
        temperature=0.2,
    )
    return _parse(answer, labels)


def _opening(transcript: Transcript, limit: int) -> str:
    """Начало записи репликами, подписанными ярлыками.

    Именно подписанными: без них модель не с чем сопоставить имя, и вопрос
    «кто из них Ларин» становится неотвечаемым.
    """
    lines: list[str] = []
    length = 0
    for segment in transcript.segments:
        text = segment.text.strip()
        if not text:
            continue
        line = f"{segment.speaker}: {text}" if segment.speaker else text
        lines.append(line)
        length += len(line)
        if length >= limit:
            break
    return "\n".join(lines)


def _parse(answer: str, labels: set[str]) -> dict[str, str]:
    """Разбирает ответ построчно, оставляя только знакомые ярлыки.

    Ярлык, которого в записи нет, — признак того, что модель сочиняет, и такая
    строка отбрасывается целиком вместе с именем.
    """
    found: dict[str, str] = {}
    for line in answer.splitlines():
        matched = _PAIR.match(line)
        if not matched:
            continue
        label, name = matched.group(1).strip(), matched.group(2).strip(' ."«»')
        if label in labels and name and name.lower() not in _NOT_A_NAME:
            found[label] = name
    return found
