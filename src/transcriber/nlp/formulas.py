"""Формулы, произнесённые словами, — записью на LaTeX.

На лекции формулу проговаривают: «предел при икс стремящемся к нулю от синус
икс делить на икс равен единице». Слушавший восстанавливает по этому запись на
доске, читающий расшифровку — нет.

Сказанное при этом остаётся как есть, а запись добавляется рядом. Замер из
`config.beam_size` показал, чем платят за гладкость: всё, что оптимизирует
правдоподобие текста, начинает выбрасывать произнесённое. Расшифровке нужна
верность, поэтому формула здесь — прибавка, а не замена.

Промт русский намеренно, как и у соседей: он разбирает русскую устную речь.
"""

from __future__ import annotations

import re
from collections.abc import Iterator, Sequence

from ..models import Segment
from .chunking import chunk_segments
from .llm import LLM

_SYSTEM = (
    "Ты читаешь расшифровки лекций и записываешь формулы, произнесённые словами, "
    "на LaTeX. Опираешься только на сказанное и ничего не додумываешь."
)

_PROMPT = """Ниже пронумерованные реплики с лекции. В некоторых формула
проговорена словами — «предел при икс стремящемся к нулю от синус икс делить на
икс равен единице». Запиши такие формулы на LaTeX.

Ответь по строке на каждую реплику, где формула действительно произнесена:

номер: LaTeX

Правила:
- пропускай реплику, если формулы в ней нет, а есть только разговор о ней
  («сегодня разберёмся, что такое производная») — это не формула;
- пиши только саму формулу, без $ и без пояснений;
- если в реплике две формулы, раздели их пробелом и точкой с запятой;
- ничего не достраивай: записывай ровно то, что произнесено.

Реплики:
{lines}"""

# «12: \lim_{x \to 0} ...» — номер, двоеточие, дальше запись.
_LINE = re.compile(r"^\s*(\d+)\s*[:.)]\s*(.+?)\s*$")

# Одно правило, а не список примет: **запись стоит строки, когда она связывает
# величины, а не называет одну**. Ниже — три вида связи, и четвёртого не
# заводится: новая примета означала бы, что правило неверно.
#
# Отношение — «равно», «меньше», «стремится», «при условии».
_RELATES = re.compile(r"=|<|>|\||\\to\b|\\le|\\ge|\\approx|\\sim\b|\\in\b|\\neq?\b|\\equiv")
# Действие над двумя величинами. Степени и индексов здесь намеренно нет: они
# украшают одну величину, а не соединяют две. Стоило `^` побыть действием — и
# `\Sigma^{-1}` под словами «обратная матрица» прошёл как формула, хотя это то же
# имя. `e^{-\lambda t}` при этом не теряется: в `v = C + e^{-\lambda t}` есть и
# равенство, и сложение.
_OPERATES = re.compile(r"[+/]|\\frac|\\sum|\\int|\\prod|\\lim|\\sqrt|\\cdot|\\times|\\partial")
# Матрица, система, выкладка в несколько строк — это всегда запись, не имя.
_ENVIRONMENT = re.compile(r"\\begin\s*\{")

# `\text{...}` — это проза, набранная как формула.
_PROSE = re.compile(r"\\text(?:rm|bf|it)?\s*\{[^{}]*\}")

_PARTS = (_RELATES, _OPERATES, _ENVIRONMENT)

# Двух примет здесь нет намеренно, и убраны обе не по вкусу, а по данным.
#
# **Перечисление.** Запятая величины разделяет, а не связывает. На лекции, где
# формулы называют, она пропустила `f(x), P`, `x, y`, `\mathbf{M}, \Sigma` —
# модель перечисляла упомянутые символы, и это были четыре записи из пяти.
#
# **Функция от аргумента.** Выглядела разумно; на той же лекции пропустила
# `\eta(x)`, обозначение самого классификатора, четырьмя строками подряд под
# словами «применим алгоритм». Имя, только со скобками. Настоящие записи оттуда
# проходят и без неё: у `p(x|\omega_i)P(\omega_i)` есть черта условия.
#
# Цена обеих: `f'(x)` и `\mathcal{N}(\mu, \sigma^2)` сами по себе не пройдут.


def _is_formula(written: str) -> bool:
    """Формула ли это, или лектор просто говорил о формуле.

    Проверено на лекции про гауссовский байесовский классификатор, где формулы
    называют, а не диктуют: прежний фильтр — «есть ли хоть один символ, какой
    бывает в записи» — пропустил девять записей, и ни одна не была формулой.
    Три оказались русской фразой в `\\text{}` («алгоритм Гауссовского-Баевского
    классикатора»), шесть — одинокими символами: `\\ln` под словами «берём
    натуральный логарифм», `\\sigma` под словом «сигма».

    Читателю от них нет ничего: слово он и так прочёл, а записи не увидел.
    Поэтому проза вычёркивается, а от остатка требуется связь величин.

    **Граница проходит не по сложности записи, а по тому, связаны ли величины**,
    и это осознанно: `\\mathbf{\\Sigma}^{-1}` под словами «обратная матрица» —
    имя величины со степенью, а `p(x|\\omega_i)P(\\omega_i)` — две величины,
    связанные чертой условия, хотя символов в обоих поровну.

    Цена честная и остаётся: одинокий символ, восстановленный поверх ошибки
    распознавания («физ-ноликом» → `\\varphi_0`), не проходит. Точность здесь
    дороже полноты — девять лишних строк в расшифровке хуже, чем ни одной.
    """
    bare = _PROSE.sub("", written).strip()
    return bool(bare) and any(part.search(bare) for part in _PARTS)


def read_formulas(
    segments: Sequence[Segment], llm: LLM, *, chunk_chars: int = 6000
) -> dict[int, list[str]]:
    """Номер сегмента → формулы из него, для тех, где формула прозвучала.

    Идёт по всей записи, а не по началу: формулы разбросаны по лекции, в отличие
    от имён, которые называют при знакомстве.
    """
    found: dict[int, list[str]] = {}
    # Что уже записано за эту запись — по всей ней, а не по куску: обсуждение
    # одной формулы пересекает границу куска так же легко, как границу реплики.
    said: set[str] = set()
    # Куски идут подряд и покрывают запись целиком, поэтому счётчика довольно.
    # Искать номер по самому сегменту было бы хуже: одинаковые реплики в лекции
    # не редкость, а `id` живёт ровно до первой сборки мусора.
    first = 0

    for chunk in chunk_segments(segments, chunk_chars):
        lines = "\n".join(f"{first + shift}: {s.text.strip()}" for shift, s in enumerate(chunk))
        answer = llm.complete(
            _PROMPT.format(lines=lines), system=_SYSTEM, max_tokens=800, temperature=0.1
        )
        for number, formulas in _parse(answer, first, first + len(chunk) - 1):
            # Только то, чего ещё не написали. Одна формула на доске обсуждается
            # несколькими репликами подряд, и модель приписывает её каждой:
            # «в этой плотности появляется…», «первая слагаемая вот здесь» —
            # и обе получили `-\frac{1}{2}\ln|\Sigma_i|`, через две секунды
            # друг от друга. Читателю нужна одна запись, у первой из реплик.
            fresh = [f for f in formulas if f not in said]
            if fresh:
                found.setdefault(number, []).extend(fresh)
                said.update(fresh)
        first += len(chunk)

    return found


def _parse(answer: str, low: int, high: int) -> Iterator[tuple[int, list[str]]]:
    """Разбирает ответ построчно, отбрасывая всё, что не похоже на запись.

    Номер вне присланного куска означает, что модель считает не то, что ей дали,
    и такой строке верить нельзя.
    """
    for line in answer.splitlines():
        matched = _LINE.match(line)
        if not matched:
            continue
        number = int(matched.group(1))
        if not low <= number <= high:
            continue
        written = [
            part.strip().strip("$").strip()
            for part in matched.group(2).split(";")
            if _is_formula(part)
        ]
        if written:
            yield number, written
