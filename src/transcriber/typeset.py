"""Набор формулы картинкой — для документов, которые математику не умеют.

В окне формулу набирает Temml, и это правильный путь: MathML остаётся текстом,
его можно выделить и скопировать. В PDF и DOCX такого пути нет. reportlab
математики не знает вовсе, а Word знает свою разметку OMML, для перевода в
которую нужен XSLT из поставки самого Word — его нельзя ни взять, ни раздавать.

Поэтому здесь картинка, и она одна на оба формата: рисуется один раз, вставляется
дважды. Рисует matplotlib своим `mathtext` — разбором подмножества LaTeX, не
требующим установленного LaTeX. Проверено на настоящих формулах двух лекций:
набирается всё, включая `\\mathcal{N}(\\mu, \\sigma^2)` и дискриминант
байесовского классификатора в четыре этажа.

Цена картинки честная и её надо знать: текст в ней не выделяется и не ищется.
Поэтому исходник остаётся рядом — в PDF подписью под формулой не идёт, но в
`txt`, `md` и `json` он есть, а `md` вдобавок рисуется сам в любом просмотрщике.
"""

from __future__ import annotations

import io
from dataclasses import dataclass

# Точек на дюйм. Двести, а не семьдесят два: формула в документе должна
# оставаться чёткой при увеличении и на печати, а весит она килобайты.
DPI = 200

# Кегль, которым рисуется формула. Подобран к тексту документа (10 пт у обоих
# писателей): формула чуть крупнее строки, потому что читается как отдельная
# запись, а не как часть абзаца.
POINTS = 11.0


@dataclass(frozen=True)
class Drawn:
    """Нарисованная формула: сама картинка и её размер в пунктах.

    Размер нужен обоим вставляющим и считается здесь: картинка нарисована в
    точках при `DPI`, а документ размечается в пунктах, и переводить это в двух
    местах порознь — верный способ разойтись.
    """

    png: bytes
    width: float
    height: float


def draw(latex: str) -> Drawn | None:
    """Набирает формулу картинкой. `None` — разобрать не удалось.

    `None`, а не исключение: несобравшаяся формула не повод не сохранить
    расшифровку. Вызывающий покажет исходник, как это делает окно.
    """
    # Ленивый импорт: matplotlib тянет своё окружение на секунды, а документ
    # без формул — обычное дело, и платить за них он не должен.
    import matplotlib

    matplotlib.use("Agg")
    from matplotlib import figure

    try:
        canvas = figure.Figure(figsize=(0.01, 0.01))
        canvas.text(0, 0, f"${latex}$", fontsize=POINTS)
        buffer = io.BytesIO()
        # `tight` обрезает холст по самой формуле: иначе вокруг остаётся поле
        # заданного нами наугад размера, и в документе формула плавает.
        canvas.savefig(
            buffer, format="png", dpi=DPI, bbox_inches="tight", pad_inches=0.02, transparent=True
        )
    except Exception:
        # mathtext знает подмножество LaTeX, и модель выходит за него. Это не
        # ошибка сохранения, а причина показать запись как есть.
        return None

    png = buffer.getvalue()
    width, height = _measure(png)
    return Drawn(png=png, width=width, height=height)


def _measure(png: bytes) -> tuple[float, float]:
    """Размер картинки в пунктах, прочитанный из её заголовка.

    Из заголовка, а не у matplotlib: тот отдаёт размер холста до обрезки по
    формуле, то есть не тот, что получился. Заголовок PNG фиксирован — ширина и
    высота лежат в байтах 16–24, и разбирать его целиком незачем.
    """
    import struct

    pixels_wide, pixels_high = struct.unpack(">II", png[16:24])
    # 72 пункта в дюйме — не выбор, а определение пункта.
    return pixels_wide * 72 / DPI, pixels_high * 72 / DPI
